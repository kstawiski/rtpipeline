# Source common settings from a wrapper in this directory.
DVH_BENCH="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export RTPIPELINE_SRC="${RTPIPELINE_SRC:-$(cd "$DVH_BENCH/../.." && pwd)}"
export RTPIPELINE_PYTHON="${RTPIPELINE_PYTHON:-python}"
export DICOMPYLER_PYTHON="${DICOMPYLER_PYTHON:-$DVH_BENCH/.venv-dicompyler/bin/python}"
export PYTHONPATH="$RTPIPELINE_SRC${PYTHONPATH:+:$PYTHONPATH}"
export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1 MKL_THREADING_LAYER=GNU
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1 NUMEXPR_NUM_THREADS=1
export ITK_GLOBAL_DEFAULT_NUMBER_OF_THREADS=1 RTPIPELINE_CONTRACT_HEADER_THREADS=4
export DVH_OUTPUT_ROOT="$DVH_BENCH"
export TMPDIR="${DVH_SCRATCH:-$DVH_BENCH/scratch/${DVH_RUN_NAME:-run}}" DVH_SCRATCH="${DVH_SCRATCH:-$DVH_BENCH/scratch/${DVH_RUN_NAME:-run}}"
export MPLCONFIGDIR="$TMPDIR/matplotlib" XDG_CACHE_HOME="$TMPDIR/cache"

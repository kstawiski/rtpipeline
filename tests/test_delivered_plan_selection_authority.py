"""Independently delivered plans must not be lost to unproven equivalence.

Synthetic in-memory fixtures only. No clinical data. Every plan, dose, record
and structure set is generated by the reference-chain helpers with fresh UIDs.

Two historical defects in ``_classify_approved_doses`` are covered.

1. Equal prescription and fraction signatures were treated as revisions even
   when each plan carried its own disjoint RTRECORD sessions, so one delivered
   plan silently left ``selected_plans``.
2. A supported plan whose validated treatment dates were a strict subset of
   another plan's dates was excluded outright.

The repair retains every independently delivered plan as selected membership
while withholding a course dose grid, course prescription scalars and
dose-response eligibility until the course semantics are reconciled. It does
not sum unrelated prescriptions, add fractions across concurrent targets, or
grant readiness.
"""

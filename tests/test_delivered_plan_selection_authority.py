@pytest.mark.parametrize("changed_field", ["isocentre", "machine", "control_points", "target_uid", "frame", "structure"])
def test_one_source_proof_change_prevents_shared_record_collapse(tmp_path, changed_field):
    """Change only one field from a proven copy, avoiding confounded negatives."""
    study_uid, frame_uid, struct_uid = _ids()
    plan_a, dose_a, uid_a = _plan_and_dose(
        tmp_path, "a", struct_uid=struct_uid, study_uid=study_uid, frame_uid=frame_uid,
        plan_date="20240101", rx_gy=25.0, fractions=5, isocentre=(0.0, 0.0, 0.0),
    )
    _physical_beam(plan_a, isocentre=(0.0, 0.0, 0.0))
    plan_b, dose_b, uid_b = _strict_equivalent_copy(tmp_path, plan_a, "b")
    a = {"path": plan_a, "sop_uid": uid_a}
    b = {"path": plan_b, "sop_uid": uid_b}
    assert org._strict_plan_equivalence(b, a)[0] is True
    ds = pydicom.dcmread(plan_b)
    if changed_field == "isocentre":
        for cp in ds.BeamSequence[0].ControlPointSequence:
            cp.IsocenterPosition = [100.0, 0.0, 0.0]
    elif changed_field == "machine":
        del ds.BeamSequence[0].TreatmentMachineName
    elif changed_field == "control_points":
        del ds.BeamSequence[0].ControlPointSequence
    elif changed_field == "target_uid":
        ds.DoseReferenceSequence[0].DoseReferenceUID = generate_uid()
    elif changed_field == "frame":
        ds.FrameOfReferenceUID = generate_uid()
    else:
        ds.ReferencedStructureSetSequence[0].ReferencedSOPInstanceUID = generate_uid()
    ds.save_as(plan_b, enforce_file_format=True)
    equivalent, reason = org._strict_plan_equivalence(b, a)
    assert equivalent is False
    assert reason
    records = [
        _record_naming(tmp_path, f"shared_{i}", [uid_a, uid_b], day=date(2024, 1, 8) + timedelta(days=i))
        for i in range(3)
    ]
    records += _records(tmp_path, "a_only", uid_a, 2, start=date(2024, 1, 11))
    classified = org._classify_doses([plan_a, plan_b], [dose_a, dose_b], treatment_record_paths=records)
    _assert_unreconciled(classified, [plan_a, plan_b])


def test_same_uid_equivalence_requires_identical_source_bytes(tmp_path):
    study_uid, frame_uid, struct_uid = _ids()
    plan_a, _, uid = _plan_and_dose(
        tmp_path, "a", struct_uid=struct_uid, study_uid=study_uid, frame_uid=frame_uid,
        plan_date="20240101", rx_gy=25.0, fractions=5, isocentre=(0.0, 0.0, 0.0),
    )
    plan_b = tmp_path / "copy.dcm"
    plan_b.write_bytes(plan_a.read_bytes())
    a, b = {"path": plan_a, "sop_uid": uid}, {"path": plan_b, "sop_uid": uid}
    assert org._strict_plan_equivalence(b, a)[0] is True
    ds = pydicom.dcmread(plan_b)
    ds.RTPlanLabel = "CHANGED"
    ds.save_as(plan_b, enforce_file_format=True)
    assert org._strict_plan_equivalence(b, a) == (
        False, "same SOPInstanceUID with different source bytes"
    )

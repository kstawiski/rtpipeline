UNRECONCILED = "independent_delivered_plans_unreconciled"


def _set_isocentre(path: Path, position: tuple[float, float, float]) -> None:
    """Attach a minimal isocentre, not enough to prove physical equivalence.

    Strict-proof controls later replace this with the fuller beam fixture.
    """
    ds = pydicom.dcmread(str(path))
    control_point = Dataset()
    control_point.ControlPointIndex = 0
    control_point.IsocenterPosition = [float(value) for value in position]
    ds.BeamSequence[0].ControlPointSequence = Sequence([control_point])
    ds.save_as(str(path), enforce_file_format=True)


def _plan_and_dose(
    root: Path,
    name: str,
    *,
    struct_uid: str,
    study_uid: str,
    frame_uid: str,
    plan_date: str,
    rx_gy: float,
    fractions: int,
    isocentre: tuple[float, float, float],
    plan_uid: str | None = None,
    with_pixels: bool = False,
) -> tuple[Path, Path, str]:
    plan_uid = plan_uid or generate_uid()
    plan = _mk_plan(
        root / f"{name}_plan.dcm",
        plan_uid,
        struct_uid=struct_uid,
        study_uid=study_uid,
        frame_uid=frame_uid,
        date=plan_date,
        rx_gy=rx_gy,
        fractions=fractions,
        label=name,
    )
    _set_isocentre(plan, isocentre)
    dose = _mk_dose(
        root / f"{name}_dose.dcm",
        generate_uid(),
        plan_uid=plan_uid,
        study_uid=study_uid,
        frame_uid=frame_uid,
        with_pixels=with_pixels,
    )
    return plan, dose, plan_uid


def _records(
    root: Path, prefix: str, plan_uid: str, count: int, *, start: date
) -> list[Path]:
    return [
        _mk_record(
            root / f"{prefix}_{index:02d}.dcm",
            plan_uid,
            date=(start + timedelta(days=index)).strftime("%Y%m%d"),
        )
        for index in range(count)
    ]


def _record_referencing_both(root: Path, name: str, uids: list[str], *, day: date) -> Path:
    path = _mk_record(root / f"{name}.dcm", uids[0], date=day.strftime("%Y%m%d"))
    ds = pydicom.dcmread(str(path))
    for uid in uids[1:]:
        ref = Dataset()
        ref.ReferencedSOPClassUID = ds.ReferencedRTPlanSequence[0].ReferencedSOPClassUID
        ref.ReferencedSOPInstanceUID = uid
        ds.ReferencedRTPlanSequence.append(ref)
    ds.save_as(str(path), enforce_file_format=True)
    return path


def _ids() -> tuple[str, str, str]:
    return generate_uid(), generate_uid(), generate_uid()


def _physical_beam(path: Path, *, isocentre: tuple[float, float, float], machine: str = "SYNTHETIC_LINAC") -> None:
    """Give the single TREATMENT beam the complete source evidence the strict
    proof reads: machine, positive meterset, two control points carrying the
    gantry/collimator/couch/energy axes and the isocentre. Without these the
    plan cannot be proven equivalent to anything."""
    ds = pydicom.dcmread(str(path))
    beam = ds.BeamSequence[0]
    beam.TreatmentMachineName = machine
    beam.BeamName = "field1"
    control_points = []
    for index in range(2):
        control_point = Dataset()
        control_point.ControlPointIndex = index
        control_point.CumulativeMetersetWeight = float(index)
        control_point.GantryAngle = 0.0
        control_point.BeamLimitingDeviceAngle = 0.0
        control_point.PatientSupportAngle = 0.0
        control_point.NominalBeamEnergy = 6.0
        control_point.IsocenterPosition = [float(value) for value in isocentre]
        control_points.append(control_point)
    beam.ControlPointSequence = Sequence(control_points)
    beam.NumberOfControlPoints = 2
    ds.FractionGroupSequence[0].ReferencedBeamSequence[0].BeamMeterset = 200.0
    ds.save_as(str(path), enforce_file_format=True)


def _strict_equivalent_copy(root: Path, source: Path, label: str, *, plan_date: str = "20240102") -> tuple[Path, Path, str]:
    """Re-export the same physical plan under a new SOPInstanceUID.

    Only identity and naming change (SOPInstanceUID, label, name, beam name,
    plan date). Target dose references, fraction groups, machine, meterset,
    beam dose, control points and isocentre stay byte-equal, which is the
    evidence the strict proof requires. Returns plan path, dose path, UID.
    """
    ds = pydicom.dcmread(str(source))
    new_uid = generate_uid()
    ds.SOPInstanceUID = new_uid
    ds.file_meta.MediaStorageSOPInstanceUID = new_uid
    ds.RTPlanLabel = label
    ds.RTPlanName = label
    ds.RTPlanDate = plan_date
    ds.BeamSequence[0].BeamName = label
    plan = root / f"{label}_plan.dcm"
    ds.save_as(str(plan), enforce_file_format=True)
    dose = _mk_dose(
        root / f"{label}_dose.dcm", generate_uid(), plan_uid=new_uid,
        study_uid=str(ds.StudyInstanceUID), frame_uid=str(ds.FrameOfReferenceUID),
    )
    return plan, dose, new_uid


def _assert_unreconciled(classified, plans: list[Path]) -> None:
    assert classified.classification == UNRECONCILED
    assert sorted(map(str, classified.selected_plans)) == sorted(map(str, plans))
    assert classified.selected_doses == []
    assert classified.should_sum is False
    assert classified.prescription_plans == []
    assert any("reconcil" in warning.lower() for warning in classified.warnings)



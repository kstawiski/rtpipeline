def test_records_referencing_both_equal_plans_without_physical_proof_are_held(tmp_path):
    """A record naming two plans is not permission to erase one.

    Both plans share prescription, fractions, structure set, frame of
    reference and every delivery record, but carry no machine, meterset or
    control-point evidence, so physical equivalence cannot be proven. Both
    remain membership under the unreconciled hold.
    """
    study_uid, frame_uid, struct_uid = _ids()
    plan_a, dose_a, uid_a = _plan_and_dose(
        tmp_path, "a", struct_uid=struct_uid, study_uid=study_uid, frame_uid=frame_uid,
        plan_date="20240101", rx_gy=25.0, fractions=5, isocentre=(0.0, 0.0, 0.0),
    )
    plan_b, dose_b, uid_b = _plan_and_dose(
        tmp_path, "b", struct_uid=struct_uid, study_uid=study_uid, frame_uid=frame_uid,
        plan_date="20240102", rx_gy=25.0, fractions=5, isocentre=(0.0, 0.0, 0.0),
    )
    records = [
        _record_referencing_both(tmp_path, f"joint_{index}", [uid_a, uid_b], day=date(2024, 1, 8) + timedelta(days=index))
        for index in range(5)
    ]

    classified = org._classify_doses([plan_a, plan_b], [dose_a, dose_b], treatment_record_paths=records)

    _assert_unreconciled(classified, [plan_a, plan_b])
    assert not any("De-duplicated" in warning for warning in classified.warnings)
    assert any("not proven physically equivalent" in warning for warning in classified.warnings)


def test_records_referencing_both_plans_with_strict_physical_proof_deduplicate(tmp_path):
    """Positive control: an alternate-UID re-export of the same physical plan,
    named by every record together with the original, contributes once."""
    study_uid, frame_uid, struct_uid = _ids()
    plan_a, dose_a, uid_a = _plan_and_dose(
        tmp_path, "a", struct_uid=struct_uid, study_uid=study_uid, frame_uid=frame_uid,
        plan_date="20240101", rx_gy=25.0, fractions=5, isocentre=(10.0, 20.0, 30.0),
    )
    _physical_beam(plan_a, isocentre=(10.0, 20.0, 30.0))
    plan_b, dose_b, uid_b = _strict_equivalent_copy(tmp_path, plan_a, "b")
    records = [
        _record_referencing_both(tmp_path, f"joint_{index}", [uid_a, uid_b], day=date(2024, 1, 8) + timedelta(days=index))
        for index in range(5)
    ]

    classified = org._classify_doses([plan_a, plan_b], [dose_a, dose_b], treatment_record_paths=records)

    assert classified.classification == "plan_revisions_deduplicated"
    # Both plans cover every record; the later-dated proven-identical
    # re-export is the representative, as for any equal revision pair.
    assert classified.selected_plans == [plan_b]
    assert classified.selected_doses == [dose_b]
    assert classified.excluded_doses == [dose_a]
    assert classified.should_sum is False



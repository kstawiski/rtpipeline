# --- Production interface: organizer publication ------------------------------


def _run_organizer(root: Path, out: Path):
    config = PipelineConfig(
        root,
        out,
        out.parent / "logs",
        max_workers_override=1,
        dicom_copy_use_hardlinks=False,
        dicom_copy_dedup_by_sop_uid=False,
    )
    courses = org.organize_and_merge(config)
    dispositions = json.loads((out / RELATIVE_PATH).read_text(encoding="utf-8"))
    ledger = read_organize_ledger(out)
    return courses, dispositions, ledger


def _assert_published_unreconciled(courses, dispositions, ledger, plan_uids: list[str]) -> None:
    assert ledger["validated_course_count"] == 1
    assert ledger["technical_quarantine_count"] == 0
    assert len(courses) == 1
    contract = load_course_contract(courses[0].dirs.root)
    data = contract.data
    selected = sorted(item["sop_instance_uid"] for item in data["selected_plans"])
    assert selected == sorted(plan_uids)
    assert data["selected_doses"] == []
    assert data["dose_grid"] is None
    assert data["dose_classification"]["classification"] == UNRECONCILED
    assert data["dose_classification"]["should_sum"] is False
    assert data["dose_classification"]["prescription_plan_uids"] == []
    delivery = data["delivery"]
    assert delivery["prescribed_dose_scope"] == UNRESOLVED_INDEPENDENT_SCOPE
    assert delivery["prescribed_dose_gy"] is None
    assert delivery["resolved_prescribed_dose_total_gy"] is None
    assert delivery["delivered_dose_gy"] is None
    assert delivery["status"] == "delivery_unresolved"
    assert delivery["dose_response_eligible"] is False
    assert delivery["dose_response_ineligibility_reason_code"]
    assert data["dose_completeness"]["status"] != "eligible"
    assert data["dose_completeness"]["unselected_delivered_plan_uids"] == []
    per_plan = {item["plan_sop_uid"]: item for item in delivery["per_plan"]}
    assert set(per_plan) == set(plan_uids)
    assert all(per_plan[uid]["delivered_fraction_count"] > 0 for uid in plan_uids)
    assert all(per_plan[uid]["selected_for_dose_grid"] for uid in plan_uids)
    rows = {row["plan_uid"]: row for row in dispositions["plans"]}
    assert set(rows) == set(plan_uids)
    for uid in plan_uids:
        assert rows[uid]["disposition_type"] == "course_member", rows[uid]
        assert rows[uid]["course_id"] == courses[0].course_id
    assert dispositions["disposition_counts"] == {"course_member": len(plan_uids)}


